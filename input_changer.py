def _clean_unit_text(value: object) -> str:
    """Normalize a unit label while preserving the pieces we care about."""
    if value is None:
        return ""
    try:
        if pd.isna(value):
            return ""
    except Exception:
        pass
    text = str(value).upper().strip()
    text = text.replace("₂", "2")
    text = text.replace("$", "USD")
    text = text.replace("USUSD", "USD")
    text = re.sub(r"[^A-Z0-9/]+", "", text)
    return text


def _ng_price_to_legacy_eur_per_mwh(value: float, price_col: str, unit_text: str) -> Tuple[float, str]:
    """Convert supported NG price units to the legacy EUR/MWh value.

    The rest of this file intentionally keeps the old calculation pathway:
    it reads a country natural-gas price in EUR/MWh, then converts it to USD/MWh
    with EUR_TO_USD_CONVERSION_HELPER. To keep the downstream model unchanged,
    raw NGFS US$2010/GJ values are converted here to EUR2025/MWh-equivalent.
    """
    raw = float(value)
    col_norm = normalize_header(price_col)
    unit_norm = _clean_unit_text(unit_text)

    # Raw NGFS unit: US$2010/GJ. Convert to USD2025/MWh, then to the legacy
    # EUR/MWh-equivalent column used by the existing ammonia-price helper.
    if ("usd2010" in col_norm and "gj" in col_norm) or ("USD2010/GJ" in unit_norm):
        usd2025_per_mwh = raw * GJ_PER_MWH * NG_PRICE_USD_2010_TO_2025_MULTIPLIER
        return (
            usd2025_per_mwh * EUR_TO_USD_CONVERSION_HELPER,
            "converted_from_USD2010_per_GJ_to_EUR2025_per_MWh",
        )

    # Already real USD/MWh. Convert to the legacy EUR/MWh-equivalent value.
    if ("usd" in col_norm and "mwh" in col_norm) or ("USD2025/MWH" in unit_norm) or ("USD/MWH" in unit_norm):
        return (
            raw * EUR_TO_USD_CONVERSION_HELPER,
            "converted_from_USD_per_MWh_to_EUR_per_MWh",
        )

    # New maker script and old legacy file both provide this column. Treat it as
    # the value the downstream helper expects.
    if ("eur" in col_norm and "mwh" in col_norm) or ("EUR" in unit_norm and "MWH" in unit_norm):
        return raw, "used_legacy_EUR_per_MWh_column"

    # Backward-compatible fallback for very old files with generic column names.
    return raw, "assumed_legacy_EUR_per_MWh_column"


