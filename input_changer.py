def build_carbon_prices(
    carbon_price_path: Path,
    natural_gas_emissions_path: Path,
    iso3: str,
    country_name: str,
    output_path: Path,
) -> Dict[str, object]:
    cdf = pd.read_excel(carbon_price_path, sheet_name="carbon_prices_by_country")
    iso_col = pick_column(cdf, ["ISO", "ISO3"])
    region_col = pick_column(cdf, ["GCAM_6.0_NGFS_Region", "Region"], required=False)

    source_metadata_lines: List[str] = []
    try:
        source_meta_df = pd.read_excel(carbon_price_path, sheet_name="metadata")
        if not source_meta_df.empty:
            first_col = source_meta_df.columns[0]
            source_metadata_lines = [str(v) for v in source_meta_df[first_col].dropna().tolist()]
    except Exception:
        source_metadata_lines = []

    year_cols = []
    for col in cdf.columns:
        try:
            year_cols.append((int(str(col).strip()), col))
        except Exception:
            continue
    year_cols = sorted(year_cols)

    country_rows = cdf[cdf[iso_col].astype(str).str.upper().str.strip() == iso3.upper()]
    if country_rows.empty:
        raise ValueError(f"No carbon-price row found for {country_name} ({iso3}).")
    country_row = country_rows.iloc[0]
    country_anchor_raw = {year: float(country_row[col]) for year, col in year_cols if pd.notna(country_row[col])}

    if region_col is not None:
        eu12_rows = cdf[cdf[region_col].astype(str).str.strip().str.upper() == "EU-12"]
    else:
        eu12_rows = pd.DataFrame()
    if eu12_rows.empty:
        # Fallback to known EU-12-style members in the table if the region label is absent.
        eu12_iso = ["BGR", "CZE", "EST", "HRV", "HUN", "LTU", "LVA", "POL", "ROU", "SVK", "SVN", "CYP", "MLT"]
        eu12_rows = cdf[cdf[iso_col].astype(str).str.upper().str.strip().isin(eu12_iso)]
    if eu12_rows.empty:
        raise ValueError("Could not find EU-12 rows in the carbon price workbook.")

    eu12_anchor_raw: Dict[int, float] = {}
    for year, col in year_cols:
        values = pd.to_numeric(eu12_rows[col], errors="coerce").dropna()
        if not values.empty:
            eu12_anchor_raw[year] = float(values.mean())

    country_anchor = {
        year: float(value) * CARBON_PRICE_USD_2010_TO_2025_MULTIPLIER
        for year, value in country_anchor_raw.items()
    }
    eu12_anchor = {
        year: float(value) * CARBON_PRICE_USD_2010_TO_2025_MULTIPLIER
        for year, value in eu12_anchor_raw.items()
    }

    country_series = build_year_series(country_anchor)
    eu12_series = build_year_series(eu12_anchor)

    ng_df = pd.read_excel(natural_gas_emissions_path)
    ng_iso_col = pick_column(ng_df, ["ISO3", "ISO"])
    ng_country_col = pick_column(ng_df, ["Country"], required=False)
    ng_value_col = pick_column(ng_df, ["CO2e (gCO₂e/kWh)", "CO2e", "gCO2e/kWh", "gCO₂e/kWh"], required=True)

    ng_rows = ng_df[ng_df[ng_iso_col].astype(str).str.upper().str.strip() == iso3.upper()]
    if ng_rows.empty and ng_country_col is not None:
        ng_rows = ng_df[ng_df[ng_country_col].apply(normalize_text) == normalize_text(country_name)]
    if ng_rows.empty:
        raise ValueError(f"No natural-gas-emissions row found for {country_name} ({iso3}).")

    ng_emissions_g_per_kwh = float(pd.to_numeric(ng_rows.iloc[0][ng_value_col], errors="coerce"))
    ng_emissions_kg_per_kwh = ng_emissions_g_per_kwh / 1000.0

    out_df = pd.DataFrame({
        "year": [int(y) for y in country_series.keys()],
        "country_carbon_price_usd2025_per_tco2": [country_series[y] for y in country_series.keys()],
        "eu12_carbon_price_usd2025_per_tco2": [eu12_series[y] for y in eu12_series.keys()],
        "ng_emissions_kgco2e_per_kwh": ng_emissions_kg_per_kwh,
        "country_name": country_name,
        "iso3": iso3,
    })

    metadata_entries = [
        {"field": "source_workbook", "value": carbon_price_path.name},
        {"field": "source_sheet", "value": "carbon_prices_by_country"},
        {"field": "source_unit_reported", "value": f"US${CARBON_PRICE_SOURCE_USD_YEAR}/t CO2"},
        {"field": "output_unit", "value": f"US${CARBON_PRICE_TARGET_USD_YEAR}/t CO2"},
        {
            "field": "conversion_rule",
            "value": (
                f"Converted source carbon prices from US${CARBON_PRICE_SOURCE_USD_YEAR}/t CO2 "
                f"to US${CARBON_PRICE_TARGET_USD_YEAR}/t CO2 by multiplying each value by "
                f"{CARBON_PRICE_USD_2010_TO_2025_MULTIPLIER:.12f}"
            ),
        },
        {"field": "conversion_method", "value": CARBON_PRICE_CONVERSION_METHOD},
        {"field": "conversion_source", "value": CARBON_PRICE_CONVERSION_SOURCE},
        {"field": "conversion_source_url", "value": CARBON_PRICE_CONVERSION_URL},
        {"field": f"gdp_deflator_{CARBON_PRICE_SOURCE_USD_YEAR}", "value": US_GDP_IMPLICIT_PRICE_DEFLATOR_2010},
        {"field": f"gdp_deflator_{CARBON_PRICE_TARGET_USD_YEAR}", "value": US_GDP_IMPLICIT_PRICE_DEFLATOR_2025},
        {"field": "inflation_multiplier", "value": CARBON_PRICE_USD_2010_TO_2025_MULTIPLIER},
        {
            "field": "note",
            "value": (
                "Original carbon-price workbook metadata reports Unit: US$2010/t CO2. "
                "The model output workbook and JSON values are now on a 2025 USD basis."
            ),
        },
    ]
    if source_metadata_lines:
        metadata_entries.append(
            {
                "field": "source_metadata_excerpt",
                "value": " | ".join(source_metadata_lines[:10]),
            }
        )
    metadata_df = pd.DataFrame(metadata_entries)

    with pd.ExcelWriter(output_path, engine="openpyxl") as writer:
        out_df.to_excel(writer, index=False, sheet_name="carbon_prices_2025usd")
        metadata_df.to_excel(writer, index=False, sheet_name="metadata")

    return {
        "country_carbon_prices_usd_per_tco2": country_series,
        "eu12_carbon_prices_usd_per_tco2": eu12_series,
        "ng_emissions_gco2e_per_kwh": ng_emissions_g_per_kwh,
        "ng_emissions_kgco2e_per_kwh": ng_emissions_kg_per_kwh,
        "carbon_price_source_usd_year": int(CARBON_PRICE_SOURCE_USD_YEAR),
        "carbon_price_target_usd_year": int(CARBON_PRICE_TARGET_USD_YEAR),
        "carbon_price_usd_conversion_multiplier": float(CARBON_PRICE_USD_2010_TO_2025_MULTIPLIER),
        "carbon_price_conversion_method": CARBON_PRICE_CONVERSION_METHOD,
        "carbon_price_conversion_source": CARBON_PRICE_CONVERSION_SOURCE,
        "carbon_price_conversion_url": CARBON_PRICE_CONVERSION_URL,
    }


