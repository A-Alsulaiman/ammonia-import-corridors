def normalize_header(value: object) -> str:
    text = "" if value is None else str(value)
    text = unicodedata.normalize("NFKD", text)
    text = text.encode("ascii", "ignore").decode("ascii")
    text = text.strip().lower()
    text = re.sub(r"[^a-z0-9]+", "", text)
    return text


def normalize_text(value: object) -> str:
    if value is None:
        return ""
    try:
        if pd.isna(value):
            return ""
    except Exception:
        pass
    text = str(value)
    text = unicodedata.normalize("NFKD", text)
    text = text.encode("ascii", "ignore").decode("ascii")
    text = text.strip().upper()
    text = re.sub(r"[^A-Z0-9]+", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


def is_usa_country(iso3: object, country_name: object) -> bool:
    """Return True for USA rows using either ISO3 or common country-name labels."""
    iso_norm = normalize_text(iso3)
    country_norm = normalize_text(country_name)
    return (
        iso_norm == normalize_text(USA_LABOUR_CAP_ISO3)
        or country_norm in USA_LABOUR_CAP_COUNTRY_NAMES
    )


def sanitize_filename(name: object) -> str:
    text = str(name).strip()
    text = re.sub(r'[<>:"/\\|?*]+', "_", text)
    text = re.sub(r"\s+", " ", text).strip()
    text = text.rstrip(". ")
    return text or "unnamed"


def pick_column(df: pd.DataFrame, candidates: Sequence[str], required: bool = True) -> Optional[str]:
    normalized_map = {normalize_header(col): col for col in df.columns}
    for candidate in candidates:
        col = normalized_map.get(normalize_header(candidate))
        if col is not None:
            return col
    candidate_norms = [normalize_header(c) for c in candidates]
    for norm_col, original_col in normalized_map.items():
        if any(norm_col.startswith(cn) for cn in candidate_norms if cn):
            return original_col
    if required:
        raise KeyError(f"Could not find required column. Tried: {list(candidates)}")
    return None


def find_input_file(project_dir: Path, trade_version_dir: Path, filename: str) -> Path:
    """Find an input workbook in the model root/Trade_version, with a recursive fallback.

    The natural-gas price and emissions workbooks are generated into Trade_version
    by the new step-1 script, so those two filenames intentionally prefer
    Trade_version over a root-folder copy. Other legacy data files keep the old
    root-first lookup order.
    """
    if filename in TRADE_VERSION_PREFERRED_INPUT_FILES:
        candidates = [
            trade_version_dir / filename,
            project_dir / TRADE_VERSION_DIRNAME / filename,
            project_dir / filename,
        ]
    else:
        candidates = [
            project_dir / filename,
            trade_version_dir / filename,
            project_dir / TRADE_VERSION_DIRNAME / filename,
        ]

    # De-duplicate equivalent paths while preserving the intended priority order.
    unique_candidates: List[Path] = []
    seen_candidate_paths = set()
    for path in candidates:
        resolved_key = str(Path(path).resolve()).lower()
        if resolved_key in seen_candidate_paths:
            continue
        seen_candidate_paths.add(resolved_key)
        unique_candidates.append(path)

    for path in unique_candidates:
        if path.exists():
            return path

    search_roots: List[Path] = []
    for root in [trade_version_dir, project_dir]:
        try:
            resolved = root.resolve()
        except Exception:
            resolved = root
        if root.exists() and all((r.resolve() if r.exists() else r) != resolved for r in search_roots):
            search_roots.append(root)

    matches: List[Path] = []
    for root in search_roots:
        try:
            for path in root.rglob(filename):
                if "trade_version_results" in path.parts:
                    continue
                if path.is_file():
                    matches.append(path)
        except Exception:
            continue

    if matches:
        matches = sorted(matches, key=lambda p: (len(str(p)), str(p)))
        return matches[0]

    raise FileNotFoundError(
        f"Could not find {filename}.\n"
        "Copy it into either the Trade_version folder or the model root folder.\n"
        "Checked direct locations:\n"
        + "\n".join(f"  - {p}" for p in unique_candidates)
    )


def resolve_required_input_files(project_dir: Path, trade_version_dir: Path) -> Dict[str, Path]:
    """Resolve all country-level data workbooks and report them together."""
    required = [
        ELECTRICITY_GRID_FILENAME,
        LABOUR_COST_FILENAME,
        GLOBAL_NG_PRICE_FILENAME,
        CARBON_PRICE_FILENAME,
        NATURAL_GAS_EMISSIONS_FILENAME,
    ]

    resolved: Dict[str, Path] = {}
    missing: List[str] = []
    messages: List[str] = []

    for filename in required:
        try:
            path = find_input_file(project_dir, trade_version_dir, filename)
            resolved[filename] = path
            messages.append(f"  - {filename}: {path}")
        except FileNotFoundError:
            missing.append(filename)

    if missing:
        raise FileNotFoundError(
            "Missing required input_changer data file(s):\n"
            + "\n".join(f"  - {name}" for name in missing)
            + "\n\nPlace these files in the project root or in Trade_version, then rerun the wrapper."
        )

    print("Resolved input_changer data files:")
    print("\n".join(messages))
    return resolved


