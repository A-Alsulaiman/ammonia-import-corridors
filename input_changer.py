def select_country_rows(df: pd.DataFrame, iso3: str, country_name: str) -> pd.DataFrame:
    iso_col = pick_column(df, ["ISO3", "ISO"], required=False)
    country_col = pick_column(df, ["Country", "Country Name"], required=False)

    if iso_col is not None:
        rows = df[df[iso_col].astype(str).str.upper().str.strip() == iso3.upper()]
        if not rows.empty:
            return rows.copy()

    if country_col is not None:
        target = normalize_text(country_name)
        rows = df[df[country_col].apply(normalize_text) == target]
        if not rows.empty:
            return rows.copy()

    raise ValueError(f"No rows found for {country_name} ({iso3}) in input table.")


def build_electricity_mix(
    source_path: Path,
    iso3: str,
    country_name: str,
    output_path: Path,
) -> pd.DataFrame:
    source_df = pd.read_excel(source_path)
    country_df = select_country_rows(source_df, iso3, country_name)

    year_col = pick_column(country_df, ["Year"])
    country_df[year_col] = pd.to_numeric(country_df[year_col], errors="coerce")
    country_df = country_df.dropna(subset=[year_col]).copy()

    raw_cols = {
        "oil": pick_column(country_df, ["oil"], required=False),
        "gas": pick_column(country_df, ["gas", "natural gas"], required=False),
        "coal": pick_column(country_df, ["coal"], required=False),
        "nuclear": pick_column(country_df, ["nuclear"], required=False),
        "hydro": pick_column(country_df, ["hydro"], required=False),
        "renewables": pick_column(country_df, ["renewables", "renewable"], required=False),
        "other": pick_column(country_df, ["other"], required=False),
    }

    available_years = sorted(int(y) for y in country_df[year_col].dropna().unique())

    def value_for(raw_key: str, target_year: int) -> float:
        col = raw_cols.get(raw_key)
        if col is None:
            return 0.0
        anchors = {}
        for yr in available_years:
            subset = country_df[country_df[year_col] == yr]
            if subset.empty:
                continue
            value = pd.to_numeric(subset[col], errors="coerce").mean()
            if pd.notna(value):
                anchors[int(yr)] = float(value)
        if not anchors:
            return 0.0
        return interpolate_from_anchor_values(anchors, target_year)

    anchor_rows = []
    for year in sorted(AEO_TARGET_ROWS):
        row = {
            "oil": value_for("oil", year),
            "natural gas": value_for("gas", year),
            "coal": value_for("coal", year),
            "nuclear": value_for("nuclear", year),
            "renewables": (
                value_for("hydro", year)
                + value_for("renewables", year)
                + value_for("other", year)
            ),
        }
        total = sum(max(0.0, float(v)) for v in row.values())
        if total <= 0:
            raise ValueError(f"Electricity mix for {country_name} ({iso3}) has zero total in {year}.")
        row = {k: max(0.0, float(v)) / total for k, v in row.items()}
        row["Year"] = year
        anchor_rows.append(row)

    anchor_df = pd.DataFrame(anchor_rows)

    interpolated = pd.DataFrame(index=range(1, AEO_FINAL_ROW + 1), columns=["oil", "natural gas", "coal", "nuclear", "renewables"])
    for year, target_row in AEO_TARGET_ROWS.items():
        values = anchor_df.loc[anchor_df["Year"] == year, ["oil", "natural gas", "coal", "nuclear", "renewables"]].iloc[0]
        interpolated.loc[target_row, :] = values.values

    interpolated = interpolated.apply(pd.to_numeric, errors="coerce")
    interpolated = interpolated.interpolate(method="linear", axis=0)
    interpolated.loc[AEO_TARGET_ROWS[2050] + 1 :, :] = interpolated.loc[AEO_TARGET_ROWS[2050], :].values
    interpolated = interpolated.bfill().ffill()
    interpolated = interpolated.reset_index(drop=True)

    write_excel_two_identical_sheets(interpolated, output_path)
    return interpolated


