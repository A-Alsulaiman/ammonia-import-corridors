def ensure_optimization_capacity_factor_patch(optimization_script: Path) -> None:
    """Patch optimization.py so hourly CF lists are kept as one object column.

    Some versions of optimization.py do:

        pd.DataFrame(capacity_factors).transpose()

    where each dictionary value is an 8760-hour list. Newer pandas expands that
    list into 8760 columns, then the legacy code tries to rename those columns to
    a single column named 'CFs', which raises:

        ValueError: Length mismatch: Expected axis has 8760 elements, new values have 1 elements

    The model logic later expects one object column called CFs, where each cell is
    the hourly list. pd.Series(...).to_frame() preserves that shape.
    """
    if not optimization_script.exists():
        raise FileNotFoundError(f"Cannot patch missing optimization script: {optimization_script}")

    text = optimization_script.read_text(encoding="utf-8")
    if "pd.Series(capacity_factors, name='CFs').to_frame()" in text or 'pd.Series(capacity_factors, name="CFs").to_frame()' in text:
        print("optimization.py capacity-factor table patch already present.")
        return

    old_block_variants = [
        """    capacity_factor_df = pd.DataFrame(capacity_factors).transpose()\n    columns_names = ['CFs']\n    capacity_factor_df.columns = columns_names\n    capacity_factor_df.sort_index(inplace=True)""",
        """    capacity_factor_df = pd.DataFrame(capacity_factors).transpose()\r\n    columns_names = ['CFs']\r\n    capacity_factor_df.columns = columns_names\r\n    capacity_factor_df.sort_index(inplace=True)""",
    ]

    new_block = """    # Build a one-column object table where each cell contains the full hourly CF list.
    # Using DataFrame(capacity_factors).T expands the 8760-hour list into 8760 columns
    # in newer pandas versions, which breaks the legacy column rename to ['CFs'].
    capacity_factor_df = pd.Series(capacity_factors, name='CFs').to_frame()
    if not isinstance(capacity_factor_df.index, pd.MultiIndex):
        capacity_factor_df.index = pd.MultiIndex.from_tuples(
            capacity_factor_df.index,
            names=['year', 'city', 'country', 'type'],
        )
    else:
        capacity_factor_df.index = capacity_factor_df.index.set_names(['year', 'city', 'country', 'type'])
    capacity_factor_df.sort_index(inplace=True)"""

    updated = None
    for old_block in old_block_variants:
        if old_block in text:
            updated = text.replace(old_block, new_block)
            break

    if updated is None:
        # More tolerant regex fallback: match the exact four logical statements even if spacing changed.
        import re
        pattern = re.compile(
            r"(?P<indent>[ \t]*)capacity_factor_df\s*=\s*pd\.DataFrame\(capacity_factors\)\.transpose\(\)\s*\n"
            r"(?P=indent)columns_names\s*=\s*\['CFs'\]\s*\n"
            r"(?P=indent)capacity_factor_df\.columns\s*=\s*columns_names\s*\n"
            r"(?P=indent)capacity_factor_df\.sort_index\(inplace=True\)",
            flags=re.MULTILINE,
        )
        match = pattern.search(text)
        if match:
            updated = pattern.sub(new_block, text, count=1)

    if updated is None:
        raise RuntimeError(
            "Could not automatically patch optimization.py. Search for the block that builds "
            "capacity_factor_df from capacity_factors and replace it with the pd.Series(...).to_frame() block."
        )

    backup = optimization_script.with_suffix(optimization_script.suffix + ".bak_capacity_factor")
    if not backup.exists():
        backup.write_text(text, encoding="utf-8")
    optimization_script.write_text(updated, encoding="utf-8")
    print(f"Patched optimization.py capacity-factor table shape. Backup: {backup}")


