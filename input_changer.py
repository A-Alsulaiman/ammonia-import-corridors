def prepare_country_inputs(args: argparse.Namespace) -> Dict[str, object]:
    project_dir = Path(args.project_dir).resolve()
    trade_version_dir = Path(args.trade_version_dir).resolve() if args.trade_version_dir else project_dir / TRADE_VERSION_DIRNAME
    country_folder = Path(args.country_folder).resolve()
    npv_results_dir = Path(args.npv_results_dir).resolve() if args.npv_results_dir else country_folder / "npv results"
    power_markets_dir = ensure_dir(project_dir / POWER_MARKETS_DIRNAME)
    ensure_dir(npv_results_dir)

    ap_location_path = Path(args.ap_location).resolve()
    ammonia_costs_path = Path(args.ammonia_costs).resolve()
    chosen_ports_path = Path(args.chosen_ports).resolve() if args.chosen_ports else None

    print("=" * 100)
    print(f"Preparing probabilistic model inputs for {args.country_name} ({args.country_iso3})")
    print(f"Project directory:      {project_dir}")
    print(f"Trade_version folder:   {trade_version_dir}")
    print(f"Country folder:         {country_folder}")
    print(f"NPV results directory:  {npv_results_dir}")
    print("=" * 100)

    resolved_inputs = resolve_required_input_files(project_dir, trade_version_dir)
    electricity_grid_path = resolved_inputs[ELECTRICITY_GRID_FILENAME]
    labour_path = resolved_inputs[LABOUR_COST_FILENAME]
    ng_price_path = resolved_inputs[GLOBAL_NG_PRICE_FILENAME]
    carbon_price_path = resolved_inputs[CARBON_PRICE_FILENAME]
    ng_emissions_path = resolved_inputs[NATURAL_GAS_EMISSIONS_FILENAME]

    # 1) AP site workbook expected by optimization.py
    ap_expected_path = power_markets_dir / AP_LOCATION_EXPECTED_FILENAME
    shutil.copy2(ap_location_path, ap_expected_path)
    shutil.copy2(ap_location_path, npv_results_dir / f"AP_location_dataset_{args.country_iso3}_for_model.xlsx")

    # 2) Electricity mix workbook expected by _path_dependent_data_handling.py
    aeo_country_path = npv_results_dir / AEO_OUTPUT_FILENAME
    build_electricity_mix(electricity_grid_path, args.country_iso3, args.country_name, aeo_country_path)
    shutil.copy2(aeo_country_path, project_dir / AEO_OUTPUT_FILENAME)
    print(f"Wrote electricity mix: {aeo_country_path}")

    # 3) Labour
    labour_info = project_labour_cost(
        source_path=labour_path,
        iso3=args.country_iso3,
        country_name=args.country_name,
        output_path=npv_results_dir / "projected_labour_costs.xlsx",
    )
    print(f"Projected operator pay: {labour_info['operator_pay_usd_per_hour']:.2f} USD/hour")
    if labour_info.get("usa_labour_pay_cap_applies"):
        cap_value = float(labour_info["usa_labour_pay_cap_usd_per_employee_2030"])
        uncapped_value = float(labour_info["projected_annual_pay_usd_per_employee_2030_uncapped"])
        capped_value = float(labour_info["projected_annual_pay_usd_per_employee_2030"])
        if labour_info.get("usa_labour_pay_cap_applied"):
            print(
                "USA labour cap applied for 2030 annual pay: "
                f"{uncapped_value:.2f} -> {capped_value:.2f} USD/employee/year "
                f"(cap {cap_value:.2f})."
            )
        else:
            print(
                "USA labour cap checked for 2030 annual pay and was not binding: "
                f"{uncapped_value:.2f} <= {cap_value:.2f} USD/employee/year."
            )

    # 4) Natural gas and ammonia prices
    ng_info = build_ng_and_nh3_prices(
        source_path=ng_price_path,
        iso3=args.country_iso3,
        country_name=args.country_name,
        output_path=npv_results_dir / "NG_price.xlsx",
        target_year=args.price_year,
    )
    print(f"Country NG initial price: {ng_info['country_ng_price_usd_per_mmbtu_no_carbon']:.2f} USD/MMBtu")
    print(f"EU-demand NH3 initial price: {ng_info['projected_nh3_price_usd_per_t']:.2f} USD/tNH3")

    # 5) Carbon price split and country NG emissions
    carbon_info = build_carbon_prices(
        carbon_price_path=carbon_price_path,
        natural_gas_emissions_path=ng_emissions_path,
        iso3=args.country_iso3,
        country_name=args.country_name,
        output_path=npv_results_dir / "carbon_prices_for_model.xlsx",
    )
    print(
        f"Carbon prices converted from USD{carbon_info['carbon_price_source_usd_year']} "
        f"to USD{carbon_info['carbon_price_target_usd_year']} using multiplier "
        f"{carbon_info['carbon_price_usd_conversion_multiplier']:.6f}"
    )
    print(f"Country NG emissions: {carbon_info['ng_emissions_gco2e_per_kwh']:.2f} gCO2e/kWh")

    # 6) Site-level logistics and shipping
    site_logistics_country_path = npv_results_dir / SITE_LOGISTICS_FILENAME
    site_df = build_site_logistics_and_shipping(
        ap_location_path=ap_location_path,
        ammonia_costs_path=ammonia_costs_path,
        chosen_ports_path=chosen_ports_path,
        country_folder=country_folder,
        country_name=args.country_name,
        output_path=site_logistics_country_path,
        pipeline_cost_usd_per_tkm=args.pipeline_cost_usd_per_tkm,
        port_infrastructure_usd_per_tnh3=args.port_infrastructure_usd_per_tnh3,
        shipping_year=args.shipping_year,
        shipping_decarbonisation_scenario=args.shipping_decarbonisation_scenario,
        eur_to_usd_rate=args.eur_to_usd_rate,
        allow_missing_shipping=args.allow_missing_shipping,
    )
    site_logistics_model_path = power_markets_dir / SITE_LOGISTICS_FILENAME
    shutil.copy2(site_logistics_country_path, site_logistics_model_path)
    print(f"Wrote site logistics/shipping file: {site_logistics_country_path}")

    # 7) Update JSON before PPA/probabilistic runs.
    input_json_path = project_dir / INPUT_PARAMETERS_FILENAME
    update_input_parameters_json(
        input_json_path=input_json_path,
        npv_results_dir=npv_results_dir,
        labour_info=labour_info,
        ng_info=ng_info,
        carbon_info=carbon_info,
        site_logistics_relative_path=str(Path(POWER_MARKETS_DIRNAME) / SITE_LOGISTICS_FILENAME),
        pipeline_cost_usd_per_tkm=args.pipeline_cost_usd_per_tkm,
        port_infrastructure_usd_per_tnh3=args.port_infrastructure_usd_per_tnh3,
    )
    pd.DataFrame([{"European_subsidy_rate": 0}]).to_excel(npv_results_dir / "subsidy_value.xlsx", index=False)
    print(f"Updated input_parameters.json and saved country-specific copy in {npv_results_dir}")

    # 8) Run renewable optimization and PPA model if requested.
    optimization_script = project_dir / "optimization.py"
    ppa_script = project_dir / "PPA_model_testing.py"
    optimization_output = power_markets_dir / OPTIMIZATION_RESULTS_FILENAME
    ppa_output = project_dir / PPA_OUTPUT_FILENAME

    if not args.skip_renewable_optimization:
        ensure_optimization_capacity_factor_patch(optimization_script)
        run_python_script(optimization_script, project_dir, args.python_executable)
    else:
        print("Skipping renewable optimization because --skip-renewable-optimization was supplied.")

    if optimization_output.exists():
        shutil.copy2(optimization_output, npv_results_dir / OPTIMIZATION_RESULTS_FILENAME)
    else:
        raise FileNotFoundError(f"Expected optimization output was not found: {optimization_output}")

    if not args.skip_ppa_model:
        run_python_script(ppa_script, project_dir, args.python_executable)
    else:
        print("Skipping PPA_model_testing.py because --skip-ppa-model was supplied.")

    if ppa_output.exists():
        shutil.copy2(ppa_output, npv_results_dir / PPA_OUTPUT_FILENAME)
    else:
        raise FileNotFoundError(f"Expected PPA output was not found: {ppa_output}")

    manifest = {
        "country_name": args.country_name,
        "country_iso3": args.country_iso3,
        "npv_results_dir": str(npv_results_dir),
        "ap_location_for_model": str(ap_expected_path),
        "aeo_for_model": str(project_dir / AEO_OUTPUT_FILENAME),
        "site_logistics_for_model": str(site_logistics_model_path),
        "optimization_results_for_model": str(optimization_output),
        "ppa_output_for_model": str(ppa_output),
        "labour": labour_info,
        "natural_gas_and_ammonia": ng_info,
        "carbon": {
            "ng_emissions_gco2e_per_kwh": carbon_info["ng_emissions_gco2e_per_kwh"],
            "ng_emissions_kgco2e_per_kwh": carbon_info["ng_emissions_kgco2e_per_kwh"],
            "carbon_price_source_usd_year": carbon_info["carbon_price_source_usd_year"],
            "carbon_price_target_usd_year": carbon_info["carbon_price_target_usd_year"],
            "carbon_price_usd_conversion_multiplier": carbon_info["carbon_price_usd_conversion_multiplier"],
            "carbon_price_conversion_method": carbon_info["carbon_price_conversion_method"],
            "carbon_price_conversion_source": carbon_info["carbon_price_conversion_source"],
            "carbon_price_conversion_url": carbon_info["carbon_price_conversion_url"],
        },
        "site_count": int(len(site_df)),
        "unique_selected_ports": sorted(site_df["selected_port"].dropna().astype(str).unique().tolist()),
    }
    manifest_path = npv_results_dir / "input_changer_manifest.json"
    with open(manifest_path, "w", encoding="utf-8") as handle:
        json.dump(manifest, handle, indent=4)

    print(f"Input preparation complete. Manifest: {manifest_path}")
    print("=" * 100)
    return manifest


