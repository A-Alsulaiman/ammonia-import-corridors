def read_ap_location_with_metadata(
    ap_location_path: Path,
    ammonia_costs_path: Path,
    chosen_ports_path: Optional[Path],
    country_name: str,
) -> pd.DataFrame:
    ap = pd.read_excel(ap_location_path).copy()
    lat_col = pick_column(ap, ["lat", "latitude"])
    lon_col = pick_column(ap, ["lon", "longitude"])
    country_col = pick_column(ap, ["Country"], required=False)
    city_col = pick_column(ap, ["City"], required=False)

    if country_col is None:
        ap["Country"] = country_name
    elif country_col != "Country":
        ap = ap.rename(columns={country_col: "Country"})

    if city_col is None:
        ap["City"] = [chr(ord("A") + i) if i < 26 else f"Site_{i+1}" for i in range(len(ap))]
    elif city_col != "City":
        ap = ap.rename(columns={city_col: "City"})

    if lat_col != "lat":
        ap = ap.rename(columns={lat_col: "lat"})
    if lon_col != "lon":
        ap = ap.rename(columns={lon_col: "lon"})

    ap["lat"] = pd.to_numeric(ap["lat"], errors="coerce")
    ap["lon"] = pd.to_numeric(ap["lon"], errors="coerce")
    ap = ap.dropna(subset=["lat", "lon"]).copy()

    nearest_col = pick_column(ap, ["nearest_port", "selected_port"], required=False)
    distance_col = pick_column(ap, ["distance_km", "distance_to_port_km"], required=False)

    needs_merge = nearest_col is None or distance_col is None
    if needs_merge:
        ammonia = pd.read_csv(ammonia_costs_path)
        a_lat = pick_column(ammonia, ["lat", "latitude"])
        a_lon = pick_column(ammonia, ["lon", "longitude"])
        a_port = pick_column(ammonia, ["nearest_port", "nearest port"])
        a_dist = pick_column(ammonia, ["distance_km", "distance to port km", "distance_to_port_km"], required=False)

        merge_cols = [a_lat, a_lon, a_port] + ([a_dist] if a_dist is not None else [])
        ammonia = ammonia[merge_cols].copy()
        rename = {a_lat: "lat", a_lon: "lon", a_port: "nearest_port"}
        if a_dist is not None:
            rename[a_dist] = "distance_km"
        ammonia = ammonia.rename(columns=rename)
        ammonia["lat_key"] = pd.to_numeric(ammonia["lat"], errors="coerce").round(6)
        ammonia["lon_key"] = pd.to_numeric(ammonia["lon"], errors="coerce").round(6)
        ammonia = ammonia.drop_duplicates(["lat_key", "lon_key"])

        ap["lat_key"] = ap["lat"].round(6)
        ap["lon_key"] = ap["lon"].round(6)
        ap = ap.merge(
            ammonia[[c for c in ["lat_key", "lon_key", "nearest_port", "distance_km"] if c in ammonia.columns]],
            on=["lat_key", "lon_key"],
            how="left",
            suffixes=("", "_from_ammonia"),
        )

        if nearest_col is not None and nearest_col != "nearest_port":
            ap["nearest_port"] = ap[nearest_col].fillna(ap.get("nearest_port"))
        if distance_col is not None and distance_col != "distance_km":
            ap["distance_km"] = ap[distance_col].fillna(ap.get("distance_km"))

        ap = ap.drop(columns=[c for c in ["lat_key", "lon_key"] if c in ap.columns])

    else:
        if nearest_col != "nearest_port":
            ap = ap.rename(columns={nearest_col: "nearest_port"})
        if distance_col != "distance_km":
            ap = ap.rename(columns={distance_col: "distance_km"})

    if chosen_ports_path is not None and chosen_ports_path.exists():
        chosen = pd.read_excel(chosen_ports_path)
        c_lat = pick_column(chosen, ["lat", "latitude"])
        c_lon = pick_column(chosen, ["lon", "longitude"])
        canonical_col = pick_column(chosen, ["canonical_main_port", "selected_port", "export_port_canonical"], required=False)
        if canonical_col is not None:
            chosen = chosen[[c_lat, c_lon, canonical_col]].copy()
            chosen = chosen.rename(columns={c_lat: "lat", c_lon: "lon", canonical_col: "selected_port"})
            chosen["lat_key"] = pd.to_numeric(chosen["lat"], errors="coerce").round(6)
            chosen["lon_key"] = pd.to_numeric(chosen["lon"], errors="coerce").round(6)
            chosen = chosen.drop_duplicates(["lat_key", "lon_key"])
            ap["lat_key"] = ap["lat"].round(6)
            ap["lon_key"] = ap["lon"].round(6)
            ap = ap.merge(chosen[["lat_key", "lon_key", "selected_port"]], on=["lat_key", "lon_key"], how="left")
            ap = ap.drop(columns=["lat_key", "lon_key"])

    if "selected_port" not in ap.columns:
        ap["selected_port"] = ap["nearest_port"]
    ap["selected_port"] = ap["selected_port"].fillna(ap["nearest_port"]).astype(str).str.strip()
    ap["nearest_port"] = ap["nearest_port"].astype(str).str.strip()
    ap["distance_km"] = pd.to_numeric(ap.get("distance_km", 0.0), errors="coerce").fillna(0.0)

    return ap


def choose_shipping_summary_row(df: pd.DataFrame, year: int, decarb_scenario: str) -> pd.Series:
    work = df.copy()
    if "year" in work.columns:
        yr = pd.to_numeric(work["year"], errors="coerce")
        filtered = work[yr == int(year)]
        if not filtered.empty:
            work = filtered
    if "decarbonisation_scenario" in work.columns:
        filtered = work[work["decarbonisation_scenario"].apply(normalize_text) == normalize_text(decarb_scenario)]
        if not filtered.empty:
            work = filtered
    if "cost_eur_per_t_mid" in work.columns:
        return work.loc[pd.to_numeric(work["cost_eur_per_t_mid"], errors="coerce").idxmin()]
    return work.iloc[0]


def read_shipping_for_port(
    country_folder: Path,
    selected_port: str,
    year: int,
    decarb_scenario: str,
    eur_to_usd_rate: float,
    allow_missing: bool = False,
) -> Dict[str, object]:
    target_norm = normalize_text(selected_port)
    summary_files = sorted(country_folder.glob("*/*_summary.csv"))

    best_candidate = None
    for summary_path in summary_files:
        parent = summary_path.parent
        try:
            df = pd.read_csv(summary_path)
        except Exception:
            continue

        origin_match = False
        if "origin" in df.columns and df["origin"].apply(normalize_text).eq(target_norm).any():
            origin_match = True
        if normalize_text(parent.name) == target_norm:
            origin_match = True

        # Also allow partial matches for cases where the WPI canonical name differs
        # slightly from the local folder-safe name.
        if not origin_match:
            parent_norm = normalize_text(parent.name)
            if target_norm and (target_norm in parent_norm or parent_norm in target_norm):
                origin_match = True

        if origin_match:
            best_candidate = (summary_path, df)
            break

    if best_candidate is None:
        message = f"No shipping summary found for selected port '{selected_port}' under {country_folder}."
        if allow_missing:
            return {
                "shipping_summary_path": "",
                "shipping_cost_eur_per_tnh3": 0.0,
                "shipping_cost_usd_per_tnh3": 0.0,
                "shipping_co2_t_per_tnh3": 0.0,
                "shipping_total_co2_t": 0.0,
                "shipping_cargo_tonnes": 0.0,
                "shipping_warning": message,
            }
        raise FileNotFoundError(message)

    summary_path, df = best_candidate
    row = choose_shipping_summary_row(df, year, decarb_scenario)

    cost_col = None
    for candidate in ["cost_eur_per_t_mid", "mean_cost_eur_per_ton", "cost_eur_per_ton"]:
        if candidate in df.columns:
            cost_col = candidate
            break
    if cost_col is None:
        raise KeyError(f"Could not find a per-tonne shipping-cost column in {summary_path}.")

    co2_col = None
    for candidate in ["total_co2_t_mid", "total_co2_tonnes", "total_co2_t"]:
        if candidate in df.columns:
            co2_col = candidate
            break

    config_path = summary_path.parent / "shipping_route_config.json"
    cargo_tonnes = 50000.0
    if config_path.exists():
        try:
            with open(config_path, "r", encoding="utf-8") as handle:
                cfg = json.load(handle)
            cargo_tonnes = float(cfg.get("cargo_tonnes", cargo_tonnes))
        except Exception:
            pass

    cost_eur = float(pd.to_numeric(row[cost_col], errors="coerce"))
    total_co2_t = 0.0 if co2_col is None else float(pd.to_numeric(row[co2_col], errors="coerce"))
    co2_per_t = total_co2_t / cargo_tonnes if cargo_tonnes else 0.0

    return {
        "shipping_summary_path": str(summary_path),
        "shipping_cost_eur_per_tnh3": cost_eur,
        "shipping_cost_usd_per_tnh3": cost_eur * eur_to_usd_rate,
        "shipping_co2_t_per_tnh3": co2_per_t,
        "shipping_total_co2_t": total_co2_t,
        "shipping_cargo_tonnes": cargo_tonnes,
        "shipping_warning": "",
    }


def build_site_logistics_and_shipping(
    ap_location_path: Path,
    ammonia_costs_path: Path,
    chosen_ports_path: Optional[Path],
    country_folder: Path,
    country_name: str,
    output_path: Path,
    pipeline_cost_usd_per_tkm: float,
    port_infrastructure_usd_per_tnh3: float,
    shipping_year: int,
    shipping_decarbonisation_scenario: str,
    eur_to_usd_rate: float,
    allow_missing_shipping: bool,
) -> pd.DataFrame:
    site = read_ap_location_with_metadata(ap_location_path, ammonia_costs_path, chosen_ports_path, country_name)

    site["to_port_pipeline_usd_per_tkm"] = float(pipeline_cost_usd_per_tkm)
    site["to_port_port_infrastructure_usd_per_tnh3"] = float(port_infrastructure_usd_per_tnh3)
    site["to_port_cost_usd_per_tnh3"] = (
        site["distance_km"].astype(float) * float(pipeline_cost_usd_per_tkm)
        + float(port_infrastructure_usd_per_tnh3)
    )

    shipping_rows = []
    cache: Dict[str, Dict[str, object]] = {}
    for port in site["selected_port"].astype(str).tolist():
        key = normalize_text(port)
        if key not in cache:
            cache[key] = read_shipping_for_port(
                country_folder=country_folder,
                selected_port=port,
                year=shipping_year,
                decarb_scenario=shipping_decarbonisation_scenario,
                eur_to_usd_rate=eur_to_usd_rate,
                allow_missing=allow_missing_shipping,
            )
        shipping_rows.append(cache[key])

    shipping_df = pd.DataFrame(shipping_rows)
    out = pd.concat([site.reset_index(drop=True), shipping_df.reset_index(drop=True)], axis=1)
    out.to_excel(output_path, index=False)
    return out


