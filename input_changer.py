def write_excel_two_identical_sheets(df: pd.DataFrame, path: Path, sheet1: str = "AEO22", sheet2: str = "AEO23") -> None:
    with pd.ExcelWriter(path) as writer:
        # Keep startcol=1 so pd.read_excel(..., index_col=0) in the legacy model
        # sees the actual fuel columns as data columns, matching the old helper.
        df.to_excel(writer, sheet_name=sheet1, index=False, startcol=1)
        df.to_excel(writer, sheet_name=sheet2, index=False, startcol=1)


def interpolate_from_anchor_values(anchor: Dict[int, float], target_year: int) -> float:
    clean = {int(k): float(v) for k, v in anchor.items() if pd.notna(v)}
    if not clean:
        raise ValueError("No numeric anchor values available for interpolation.")
    years = sorted(clean)
    if target_year <= years[0]:
        return clean[years[0]]
    if target_year >= years[-1]:
        return clean[years[-1]]
    return float(np.interp(target_year, years, [clean[y] for y in years]))


def build_year_series(anchor: Dict[int, float], start_year: int = 2027, end_year: int = 2070) -> Dict[str, float]:
    return {
        str(year): float(interpolate_from_anchor_values(anchor, year))
        for year in range(start_year, end_year + 1)
    }


