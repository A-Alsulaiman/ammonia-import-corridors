def project_labour_cost(
    source_path: Path,
    iso3: str,
    country_name: str,
    output_path: Path,
) -> Dict[str, object]:
    df = pd.read_excel(source_path)
    iso_col = pick_column(df, ["ISO3", "ISO"], required=False)
    country_col = pick_column(df, ["Country"], required=False)
    year_col = pick_column(df, ["Year"])
    activity_col = pick_column(df, ["ActivityCode", "Activity Code"])
    pay_col = pick_column(df, ["AnnualPay_USD_per_employee", "Annual Pay USD per employee", "AnnualPay USD"], required=True)

    if iso_col is not None:
        cdf = df[df[iso_col].astype(str).str.upper().str.strip() == iso3.upper()].copy()
    else:
        cdf = pd.DataFrame()
    if cdf.empty and country_col is not None:
        cdf = df[df[country_col].apply(normalize_text) == normalize_text(country_name)].copy()
    if cdf.empty:
        raise ValueError(f"No labour-cost rows found for {country_name} ({iso3}).")

    cdf[year_col] = pd.to_numeric(cdf[year_col], errors="coerce")
    cdf[pay_col] = pd.to_numeric(cdf[pay_col], errors="coerce")
    cdf["_activity_code_norm"] = cdf[activity_col].astype(str).str.replace(r"\.0$", "", regex=True).str.strip()

    selected = None
    selected_code = None
    projection_method = None

    for code in LABOUR_ACTIVITY_PRIORITY:
        subset = cdf[(cdf["_activity_code_norm"] == code) & cdf[year_col].notna() & cdf[pay_col].notna()].copy()
        subset = subset.sort_values(year_col)
        if len(subset) >= 2:
            x = subset[year_col].astype(float).to_numpy()
            y = subset[pay_col].astype(float).to_numpy()
            slope, intercept = np.polyfit(x, y, deg=1)
            projected_annual = float(slope * 2030 + intercept)
            selected = subset
            selected_code = code
            projection_method = "linear_regression"
            break
        if len(subset) == 1 and selected is None:
            selected = subset
            selected_code = code
            projected_annual = float(subset[pay_col].iloc[0])
            projection_method = "single_point_constant"

    if selected is None or selected.empty:
        raise ValueError(f"No usable labour-cost activity-code rows found for {country_name} ({iso3}).")

    projected_annual_uncapped = max(0.0, float(projected_annual))
    usa_labour_cap_applies = is_usa_country(iso3=iso3, country_name=country_name)
    usa_labour_cap_applied = False
    usa_labour_cap_value = None

    if usa_labour_cap_applies:
        usa_labour_cap_value = float(USA_LABOUR_CAP_ANNUAL_PAY_USD_PER_EMPLOYEE_2030)
        projected_annual = min(projected_annual_uncapped, usa_labour_cap_value)
        usa_labour_cap_applied = projected_annual_uncapped > usa_labour_cap_value
    else:
        projected_annual = projected_annual_uncapped

    operator_pay_hourly = projected_annual / ANNUAL_HOURS_PER_OPERATOR

    result = {
        "operator_pay_usd_per_hour": operator_pay_hourly,
        "projected_annual_pay_usd_per_employee_2030": projected_annual,
        "projected_annual_pay_usd_per_employee_2030_uncapped": projected_annual_uncapped,
        "usa_labour_pay_cap_usd_per_employee_2030": usa_labour_cap_value,
        "usa_labour_pay_cap_applies": bool(usa_labour_cap_applies),
        "usa_labour_pay_cap_applied": bool(usa_labour_cap_applied),
        "activity_code_used": selected_code,
        "projection_method": projection_method,
        "source_year_min": int(selected[year_col].min()),
        "source_year_max": int(selected[year_col].max()),
        "country_name": country_name,
        "iso3": iso3,
    }
    pd.DataFrame([result]).to_excel(output_path, index=False)
    return result


